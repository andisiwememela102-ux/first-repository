# Declare the variables to be used in the conversion process
num1 = 99.23
num2 = 23
num3 = 150
string_num = "100"

# Convert the variables to the desired types
converted_num1 = int(num1)  

# convert num2 to a float
converted_num2 = float(num2)

# convert num3 to a string
converted_num3 = str(num3)

# convert string_num to an integer
converted_string_num = int(string_num)

# Print the converted values
print("Converted num1 (float to int):", converted_num1)
print("Converted num2 (int to float):", converted_num2)
print("Converted num3 (int to string):", converted_num3)
print("Converted string_num (string to int):", converted_string_num)